#!/usr/bin/env bash
# =============================================================================
# vm/lib/flow-persistent.sh — persistent VM flow (default, no --testing)
# =============================================================================
# Sourced by vm/vm.sh alongside core.sh. Builds a persistent, reusable libvirt
# VM: boots the Arch live ISO, serves the installer over HTTP on the libvirt
# gateway, types `curl …|bash` into the spice console via send-key, waits for
# the installer to power off, then reboots into the installed system for
# interactive use (virt-manager).
#
# Consumes (set by vm.sh): VM_NAME, VM_DISK_SIZES[], VM_RAM_MB, VM_VCPUS,
# INSTALL_CONFIG_CONTENT, VM_FIXTURE_FILES[], VM_SCRIPT_DIR, RECREATE.
# =============================================================================

FLOW_PERSIST_DIR="$(cd "${BASH_SOURCE[0]%/*}" && pwd)"
# core.sh provides the shared host-side functions + defaults; guard-source so
# vm.sh sourcing core first does not double-source.
# shellcheck source=./core.sh
[[ "$(type -t vm_resolve_iso)" == function ]] \
  || source "${FLOW_PERSIST_DIR}/core.sh"
# shellcheck source=./sentinel-watcher.sh
source "${FLOW_PERSIST_DIR}/sentinel-watcher.sh"
# shellcheck source=./seed-generator.sh
# Only for _seed_generator_esp_serial_lines — route the INSTALLED kernel to
# serial so a broken persistent boot is never silent (ADR 0099).
source "${FLOW_PERSIST_DIR}/seed-generator.sh"

# Per-flow virt-install graphics (core._core_vm_create appends these). niri (and any
# Wayland compositor) REJECTS software EGL — a display-only virtio-gpu renders a
# black screen. So give the guest a virgl 3D device (hardware EGL) via spice-gl
# when the host has a DRM render node; else fall back to display-only (a
# headless/no-GPU host still builds, sans an interactive Wayland desktop).
_flow_persistent_render_node() {
  local render_node
  for render_node in "${VM_RENDER_NODE:-}" /dev/dri/renderD*; do
    [[ -n "$render_node" && -e "$render_node" ]] \
      && { printf '%s\n' "$render_node"; return 0; }
  done
  return 1
}
if _rnode="$(_flow_persistent_render_node)"; then
  # shellcheck disable=SC2054 # each --graphics value is one virt-install arg
  FLOW_GRAPHICS_ARGS=(
    --video model.type=virtio,model.acceleration.accel3d=on
    --graphics "spice,listen=none,gl.enable=on,gl.rendernode=${_rnode}"
    --channel spicevmc)
else
  warn "No DRM render node — VM gets a display-only GPU (no Wayland desktop)."
  # shellcheck disable=SC2054 # spice,listen=none is one virt-install argument
  FLOW_GRAPHICS_ARGS=(--graphics spice,listen=none --video virtio \
                      --channel spicevmc)
fi

# Flow defaults (env overrides win; timeouts also resolved env>profile>here).
: "${CACHE_DIR:=${FLOW_PERSIST_DIR%/lib}/.vm-cache}"
: "${HTTP_PORT:=9876}"
: "${BOOT_TIMEOUT_SEC:=300}"
: "${INSTALL_TIMEOUT_SEC:=3600}"

_HTTP_PID=""

# =============================================================================
# HARNESS SSH KEY — local-only debug key the host uses to enter the guest
# =============================================================================
# Persistent VMs enable sshd + authorize this key so the host (and an agent
# driving it) can SSH in to diagnose the installed desktop. The key lives under
# the git-ignored .vm-cache; generate it on first use so a fresh checkout is
# self-contained. Never a production install artifact.
_flow_persistent_key_path() { printf '%s\n' "${CACHE_DIR}/harness_ed25519"; }

_flow_persistent_ensure_key() {
  local key; key="$(_flow_persistent_key_path)"
  [[ -f "$key" && -f "${key}.pub" ]] && return 0
  command_exists ssh-keygen || error "ssh-keygen not found — install openssh."
  info "Generating harness SSH key at ${key}."
  ssh-keygen -t ed25519 -N '' -C arch-vm-harness -f "$key" >/dev/null
}

# =============================================================================
# SEED — live-ISO access seed (key + serial autologin + sshd), NO installer
# =============================================================================
# The seed makes the LIVE ISO inspectable at FIRST BOOT, independently of the
# typed installer payload (ADR 0099). The installer is still typed via
# curl|bash; this seed carries NO install runcmd. Its whole job is the two
# always-on inspection channels a failed install needs:
#   - the harness key authorized on the live ISO's root, sshd up;
#   - a root autologin getty on ttyS0, so an agent can drive the live env over
#     `virsh console` with no network at all.
# So a failure UPSTREAM of the typed payload (no boot past login, no network,
# curl/HTTP fails) no longer locks the host out of both channels — the gap the
# old in-payload authorize left. The install log is still a FILE, never streamed
# to serial (a slow reader wedges pacman); the agent reads it over these
# channels on demand.
_flow_persistent_render_seed_user_data() {
  local pubkey="$1"
  cat <<EOF
#cloud-config
# Generated by vm/lib/flow-persistent.sh — persistent-flow live-ISO access seed.
# Consumed by archiso's NoCloud datasource on first boot. NO install runcmd:
# the installer is typed via curl|bash; this only seeds SSH + serial (ADR 0099).
runcmd:
  - |
    set -x
    # Live-ISO SSH: authorize the harness key + ensure sshd, so the host can SSH
    # in even when the typed installer payload never runs.
    install -d -m700 /root/.ssh
    printf '%s\n' '${pubkey}' >> /root/.ssh/authorized_keys
    systemctl enable --now sshd 2>/dev/null || systemctl start sshd || true
    # Serial fallback: a root autologin getty on ttyS0 — the zero-network channel
    # an agent drives over \`virsh console\` (survives no-DHCP, no-sshd, a panic).
$(_core_serial_autologin_root_lines)
EOF
}

_flow_build_seed() {
  local pubkey="$1"
  local user_data="${CACHE_DIR}/${VM_NAME}-user-data"
  local seed_iso="${CACHE_DIR}/${VM_NAME}-seed.iso"
  _flow_persistent_render_seed_user_data "${pubkey}" > "${user_data}"
  cloud-localds "${seed_iso}" "${user_data}" >/dev/null \
    || error "cloud-localds failed for ${user_data}"
  [[ -s "${seed_iso}" ]] || \
    error "cloud-localds produced empty seed at ${seed_iso}"
  printf '%s\n' "${seed_iso}"
}

# _flow_persistent_pin_disks_function — print a guest-side `pin_disks <config> [by-id-dir]`:
# each config string /dev/sdX becomes the by-id path of the disk the harness
# put on that port (serial vmdisk<i>, _core_vm_create). The live ISO may name SATA
# disks out of port order (tuned 20261008: sdb was the 20G disk). An older VM
# without the serials keeps its /dev/sdX.
_flow_persistent_pin_disks_function() {
  cat <<'FN'
pin_disks() {
  local c="$1" d="${2:-/dev/disk/by-id}" i=0 l p
  for l in a b c d e f g h; do
    p="$d/ata-QEMU_HARDDISK_vmdisk$i"; i=$((i + 1))
    [ -e "$p" ] || continue
    jq --arg a "/dev/sd$l" --arg b "$p" \
      'walk(if . == $a then $b else . end)' "$c" > "$c.n" && mv "$c.n" "$c"
  done
}
FN
}

# =============================================================================
# INSTALLER SCRIPT (served over HTTP, launched via send-key)
# =============================================================================
_flow_persistent_render_installer_script() {
  local repo_url="$1" pubkey="$2" primary_user="${3:-aquastias}" config_b64
  config_b64="$(printf '%s' "${INSTALL_CONFIG_CONTENT}" | base64 -w 0)"
  # Forced-skew gate (ADR 0137): when the host exports
  # ARCHZFS_LTS_CEILING_OVERRIDE, thread it into the guest so the install
  # exercises the archzfs LTS ceiling pin even after archzfs has caught up to
  # the mirror (no live skew). Empty ⇒ no line injected ⇒ happy path.
  local skew_line=""
  [[ -n "${ARCHZFS_LTS_CEILING_OVERRIDE:-}" ]] \
    && skew_line="export ARCHZFS_LTS_CEILING_OVERRIDE='${ARCHZFS_LTS_CEILING_OVERRIDE}'"
  # Feature Audit (ADR 0152): a clean install powers off right after the
  # sentinel, taking /root/install.log with it, so wait (bounded) for the host
  # to pull the log over the seed's SSH before powering off.
  local hold_line=""
  # shellcheck disable=SC2016 # expands in the guest, not here
  [[ -n "${VM_HOLD_FOR_LOG_PULL:-}" ]] \
    && hold_line='for _ in $(seq 300); do
  [ -f /root/.log-pulled ] && break; sleep 1
done'
  cat <<EOF
#!/usr/bin/env bash
set -euo pipefail
set -x
# A death before install.sh runs (bad clone, pacman error, a payload bug) must
# still reach the host as a sentinel, or it waits out the whole install
# timeout on a shell that is already gone.
rm -f /root/.install-exit
_early_exit() {
  rc=\$?
  [ -f /root/.install-exit ] && return
  printf '\r\n===INSTALLER-EXIT-%d===\r\n' "\$((rc ? rc : 98))" > /dev/ttyS0
}
trap _early_exit EXIT
# The preamble's output goes to the pulled log too: a death here (ufw
# 20261008) otherwise leaves nothing to read. Restored before install.sh.
exec 3>&1 4>&2 > >(tee -a /root/install.log) 2>&1
# network steps retried (a mirror/GitHub blip); _retry's markers, so the
# Feature Audit folds a recovered attempt (ADR 0152)
_try() {
  local i rc
  for i in 1 2 3; do
    echo "[ATTEMPT] \$i/3 \$1"
    "\$@" && return 0
    rc=\$?; [ "\$i" = 3 ] && return "\$rc"
    echo "[RETRY] attempt \$i/3 of \$1 returned \$rc; trying again"
    sleep \$((i * 10))
  done
}
_clone() { rm -rf /root/dotfiles; git clone ${repo_url} /root/dotfiles; }
# The harness key + serial autologin are authorized by the cloud-init seed at
# first boot (ADR 0099), independent of this payload — so a failure before this
# script even runs still leaves the live ISO reachable. This payload only clones
# + runs the installer.
pacman-key --init
pacman-key --populate archlinux
# jq patches the config (below) before the installer's own toolchain preflight.
_try pacman -Sy --noconfirm --needed git jq
_try _clone
printf '%s' '${config_b64}' | base64 -d > /root/dotfiles/.installer/install.jsonc
cd /root/dotfiles/.installer
$(_flow_persistent_pin_disks_function)
pin_disks install.jsonc
# Persistent debug VMs only: enable sshd + authorize the harness key so the host
# can SSH into the installed guest to diagnose the desktop. The clone is
# disposable, so patching the committed profile in place never leaks upstream.
# The curated niri/Noctalia config is served by the adapter via /etc/skel (ADR
# 0095), NOT stowed by the installer — so no dotfiles_repo is set here.
jq '.options.ssh.enabled = true' install.jsonc > install.jsonc.n \\
  && mv install.jsonc.n install.jsonc
source lib/jsonc.sh
_uprof="users/${primary_user}/profile.jsonc"
[[ -f "\$_uprof" ]] || _uprof="users/core/profile.jsonc"
jsonc_strip "\$_uprof" \\
  | jq --arg k '${pubkey}' \\
      '.ssh_authorized_keys = ((.ssh_authorized_keys // []) + [\$k])' \\
  > "\$_uprof.n" && mv "\$_uprof.n" "\$_uprof"
# Test-only preset passphrases so an encrypted/SOPS profile installs unattended
# (no-ops on profiles without encryption or secrets). Disposable VMs only.
export INSTALL_ENC_PASSPHRASE='testtest'
export SECRETS_AGE_PASSPHRASE='test'
# Route every loader's installed kernel console to serial (efistub's cmdline
# lives in NVRAM, so it can't be patched after install like grub.cfg).
export INSTALL_EXTRA_CMDLINE='console=ttyS0,115200'
$(_seed_generator_env_exports plain)
# Forced-skew gate (ADR 0137): fake-low archzfs LTS ceiling, host-injected. A
# blank line when unset — the happy path is untouched.
${skew_line}
# Capture the install to a file (a FILE tee is safe; serial is not — a slow
# reader wedges pacman). Then emit an exit sentinel on BOTH success and failure
# so the host can tell a failed install from a hang, and on failure HOLD the
# live ISO up (no poweroff) so the log at /root/install.log is inspectable over
# the seed's SSH + serial channels (ADR 0099). Only a clean install powers off,
# so the flow reboots into the installed system.
exec 1>&3 2>&4 3>&- 4>&-
set +e
./install.sh --unattended install.jsonc 2>&1 | tee -a /root/install.log
rc=\${PIPESTATUS[0]}
set -e
printf '%d\n' "\$rc" > /root/.install-exit
# Leading CRLF so the sentinel starts a fresh line even when the login shell has
# already redrawn its prompt on the current one — the watcher regex is anchored
# to line start, so an appended sentinel (prompt + escapes + marker) never
# matched and the host waited the full timeout on a successful install.
printf '\r\n===INSTALLER-EXIT-%d===\r\n' "\$rc" > /dev/ttyS0
sync
${hold_line}
if [ "\$rc" -eq 0 ]; then
  # Route the INSTALLED kernel + LUKS/zfs unlock prompt to serial so a
  # broken boot of this debug VM is never silent (ADR 0099). install.sh has
  # exported the pool by now, so /mnt is free for the ESP mount.
$(_seed_generator_esp_serial_lines)
  poweroff
fi
EOF
}

# Map a single character to one or more virsh key names.
_flow_persistent_char_to_keys() {
  case "$1" in
    [a-z]) printf 'KEY_%s'            "${1^^}" ;;
    [0-9]) printf 'KEY_%s'            "$1"     ;;
    ' ')   printf 'KEY_SPACE'                  ;;
    '.')   printf 'KEY_DOT'                    ;;
    '/')   printf 'KEY_SLASH'                  ;;
    '-')   printf 'KEY_MINUS'                  ;;
    ':')   printf 'KEY_LEFTSHIFT KEY_SEMICOLON' ;;
    '|')   printf 'KEY_LEFTSHIFT KEY_BACKSLASH' ;;
    *)     return 1 ;;
  esac
}

_flow_persistent_type_into_console() {
  local vm="$1" text="$2" i char keys
  for ((i = 0; i < ${#text}; i++)); do
    char="${text:i:1}"
    if keys="$(_flow_persistent_char_to_keys "$char")"; then
      # shellcheck disable=SC2086
      virsh send-key "$vm" $keys >/dev/null 2>&1
    else
      warn "virsh send-key: skipping unmapped character '${char}'"
    fi
    sleep 0.05
  done
  virsh send-key "$vm" KEY_ENTER >/dev/null 2>&1
}

_flow_persistent_stop_http_server() {
  [[ -n "${_HTTP_PID}" ]] || return 0
  kill "${_HTTP_PID}" 2>/dev/null || true
  _HTTP_PID=""
}

_flow_persistent_launch_installer() {
  local script="${CACHE_DIR}/run"
  local pubkey; pubkey="$(cat "$(_flow_persistent_key_path).pub")"
  _flow_persistent_render_installer_script "${REPO_URL}" "$pubkey" "${PRIMARY_USER}" \
    > "${script}"

  "${FLOW_PERSIST_DIR}/serve-http.sh" "${CACHE_DIR}" "${LIBVIRT_GATEWAY}" \
    "${HTTP_PORT}" >/dev/null 2>&1 &
  _HTTP_PID=$!

  local url="http://${LIBVIRT_GATEWAY}:${HTTP_PORT}/run"
  local command_line="curl -s ${url}|bash"
  info "Sending to console: ${command_line}"
  _flow_persistent_type_into_console "${VM_NAME}" "${command_line}"
  info "Installer command sent — running inside VM."
}

# =============================================================================
# NETWORK / COMPLETION WAITS
